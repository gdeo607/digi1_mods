#!/usr/bin/env python3
"""Generate mods/digi101/sh101_tables.h: the lookup tables of the SH-101 engine.

The engine renders at 48 kHz in blocks of up to 32 samples; LFO and envelope advance once a block,
so their tables are per block of 32 samples (the rate the unit calls the render).
"""
import math, os, sys

SR = 48000.0
BLOCK = 32
ZONE = 59          # LFO and ENV each get 59 knob steps on G (see sh101.h)

def lfo_rates():
    # 101 LFO range is roughly 0.1 Hz .. 30 Hz; exponential across the zone
    out = []
    for i in range(ZONE):
        hz = 0.1 * (300.0 ** (i / (ZONE - 1)))
        out.append(int(round(hz / SR * 2 ** 32)))          # phase step a sample
    return out

def env_decays():
    # PWM envelope decay, 10 ms .. 4 s (time to fall to 1/e); per block: env -= env * k / 65536
    out = []
    for i in range(ZONE):
        tau = 0.010 * (400.0 ** (i / (ZONE - 1)))
        k = 65536.0 * (1.0 - math.exp(-BLOCK / (SR * tau)))
        out.append(max(1, int(round(k))))
    return out

def gains():
    # mixer slider 0..127 -> Q15 level; a gentle audio taper (squared), 127 = 32767
    return [int(round(32767 * (v / 127.0) ** 2)) for v in range(128)]

def port_k():
    # portamento: the pitch offset (in octaves) decays by k/65536 a 32-sample block; PORT 1..127 ->
    # time constant 2 ms .. 3 s (exponential), 0 = off
    out = [0]
    for i in range(1, 128):
        tau = 0.002 * (1500.0 ** ((i - 1) / 126.0))
        out.append(max(1, int(round(65536.0 * (1.0 - math.exp(-BLOCK / (SR * tau)))))))
    return out

def log2_tab():
    # log2(1 + i/32), Q16, i = 0..32
    return [int(round(math.log2(1 + i / 32.0) * 65536)) for i in range(33)]

def exp2_tab():
    # 2^(i/32), Q16, i = 0..32
    return [int(round(2 ** (i / 32.0) * 65536)) for i in range(33)]

# ---- the VCF (fitted to TAL-BassLine-101 recordings) -----------------------------
F0 = 440.0 * 2 ** ((0 - 69) / 12.0)       # MIDI note 0, 8.18 Hz: the bottom of the cutoff scale
FMAX = 20000.0
def vcf_g():
    # G = g / (1 + g), g = tan(pi fc / fs), Q31, fc in quarter semitones above F0 (0 .. 540 = 20 kHz)
    out = []
    for i in range(545):
        fc = min(F0 * 2 ** (i / 48.0), FMAX)
        g = math.tan(math.pi * fc / SR)
        out.append(int(round(g / (1 + g) * 2 ** 31)) if g / (1 + g) < 1 else 2 ** 31 - 1)
    return out

def vcf_cut():
    # CUT knob 0..127 (= TAL's 0..100 %) -> the pole frequency, Q16 octaves above F0: a monotone cubic
    # through the poles fitted to TAL-BassLine-101's noise takes (whole-curve fits):
    # 10 % 16.7 Hz, 30 % 43 Hz, 50 % 242 Hz, 60 % 472 Hz, 90 % 3.7 kHz, 100 % 20 kHz (its self-
    # oscillation takes); 0 % carries on the bottom slope. Resonance pulls it up as it rises (vcf_pitch):
    # 0.0516 octave a unit of k, which the 50/60/90 % points here allow for (TAL's 278 Hz at full res)
    import numpy as np
    from scipy.interpolate import PchipInterpolator
    pts = [(0, 10.4), (10, 16.7), (30, 43.0), (50, 242.0), (60, 440.0), (90, 3450.0), (100, 20000.0)]
    f = PchipInterpolator([p for p, _ in pts], [math.log2(h) for _, h in pts])
    return [int(round((float(f(v * 100.0 / 127)) - math.log2(F0)) * 65536)) for v in range(128)]

def vcf_k():
    # RES knob 0..127 -> the ladder's feedback k, Q28. Fitted to TAL-BassLine-101's noise takes at cutoff
    # 50 % (peak heights over RES 0, quiet noise, after the feedback limiter): 25 % 0.91, 50 % 1.97,
    # 75 % 3.31, 100 % 3.78 (knob 120);
    # 120..127 goes on to 4.4: self-oscillation, as on the hardware (TAL does not)
    import numpy as np
    from scipy.interpolate import PchipInterpolator
    pts = [(0, 0.0), (30, 0.91), (60, 1.97), (90, 3.31), (120, 3.78), (127, 4.40)]
    f = PchipInterpolator([a for a, _ in pts], [b for _, b in pts])
    return [int(round(float(f(v)) * 2 ** 28)) for v in range(128)]

def lfo_rate128():
    # RATE knob 0..127 -> the LFO's phase step a sample, 0.1 .. 30 Hz
    return [int(round(0.1 * 300.0 ** (i / 127.0) / SR * 2 ** 32)) for i in range(128)]

def fmt(name, ctype, vals, per=8):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) + ("u" if ctype.startswith("uint32") else "") for v in vals[i:i + per]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(vals), "\n".join(lines))

def main(path):
    s = ["/* generated by tools/gen_digi101_tables.py: do not edit */",
         "#ifndef SH101_TABLES_H", "#define SH101_TABLES_H", "#include <stdint.h>", "",
         "/* the PWM LFO's phase step a sample, 0.1 .. 30 Hz */",
         fmt("SH_LFO_INC", "uint32_t", lfo_rates(), 4),
         "/* the PWM envelope's decay a 32-sample block, Q16: 10 ms .. 4 s */",
         fmt("SH_ENV_K", "uint16_t", env_decays()),
         "/* a mixer level, 0..127 -> Q15 */",
         fmt("SH_GAIN", "uint16_t", gains()),
         "/* portamento: the pitch offset's decay a 32-sample block, Q16 (PORT 0 = off .. 127 = 3 s) */",
         fmt("SH_PORT_K", "uint16_t", port_k()),
         "/* log2(1 + i/32) and 2^(i/32), Q16, for the glide's pitch arithmetic */",
         fmt("SH_LOG2", "uint32_t", log2_tab(), 6),
         fmt("SH_EXP2", "uint32_t", exp2_tab(), 6),
         "/* the VCF: G = g / (1 + g) (Q31) every quarter semitone above 8.18 Hz to 20 kHz */",
         fmt("SH_VCF_G", "uint32_t", vcf_g(), 6),
         "/* CUT knob -> pole frequency, Q16 octaves above 8.18 Hz (TAL-BassLine-101's scale) */",
         fmt("SH_VCF_CUT", "uint32_t", vcf_cut(), 6),
         "/* RES knob -> the ladder's feedback k, Q28 (4.0 = self-oscillation) */",
         fmt("SH_VCF_K", "uint32_t", vcf_k(), 6),
         "/* RATE knob -> LFO phase step a sample, 0.1 .. 30 Hz */",
         fmt("SH_LFO_RATE", "uint32_t", lfo_rate128(), 6),
         "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(s))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "mods", "digi101", "sh101_tables.h"))
