#!/usr/bin/env python3
"""Writes mods/digitx/tx_tables.h: 2^(i/64) in Q16, i = 0..64 (Digi TX's exp2)."""
import os
t = [round(65536 * 2 ** (i / 64)) for i in range(65)]
s = "/* tx_tables.h: generated by tools/gen_tx_tables.py (2^(i/64) in Q16, i = 0..64) */\n"
s += "static const uint32_t tx_exp2_frac[65] = {\n"
for i in range(0, 65, 8):
    s += "    " + ", ".join(str(x) for x in t[i:i + 8]) + ",\n"
s += "};\n"
open(os.path.join(os.path.dirname(__file__), "..", "mods", "digitx", "tx_tables.h"), "w").write(s)
